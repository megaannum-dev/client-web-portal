class FakeStaffIdentityService:
    """§8.1 identity double for BE-17/BE-18: ensure_identity / delete_user /
    generate_set_password_link, plus a tracked (never-should-be-called)
    update_user so BE-18's "no credential mutation" invariant is asserted
    against a real call list rather than the mere absence of a mock method.

    `existing={"email": "uid"}` seeds an ADOPTED identity (ensure_identity
    returns created=False for it) -- BE-17's "adopted identity is never
    deleted on compensation" negative saga needs exactly this."""

    def __init__(self, *, existing: dict[str, str] | None = None) -> None:
        self._existing: dict[str, str] = dict(existing or {})
        self._counter = 0
        self._link_counter = 0
        self.ensure_identity_calls: list[str] = []
        self.delete_user_calls: list[str] = []
        self.generate_set_password_link_calls: list[str] = []
        self.update_user_calls: list[tuple] = []

    def ensure_identity(self, email: str, password: str | None = None) -> tuple[str, bool]:
        self.ensure_identity_calls.append(email)
        existing_uid = self._existing.get(email)
        if existing_uid is not None:
            if password is not None:
                self.update_user_calls.append((existing_uid, {"password": password}))
            return existing_uid, False
        self._counter += 1
        uid = f"fake-staff-uid-{self._counter}"
        self._existing[email] = uid
        return uid, True

    def delete_user(self, uid: str) -> None:
        self.delete_user_calls.append(uid)
        for email, existing_uid in list(self._existing.items()):
            if existing_uid == uid:
                del self._existing[email]

    def generate_set_password_link(self, email: str) -> str:
        self._link_counter += 1
        self.generate_set_password_link_calls.append(email)
        return f"https://fake-staff.invalid/set-password?email={email}&n={self._link_counter}"

    def update_user(self, uid: str, **kwargs) -> None:  # pragma: no cover -- must stay unused
        self.update_user_calls.append((uid, kwargs))


class CommitFailSession:
    """Thin proxy around a real Session: `commit()` raises the first
    `fail_times` calls, then behaves normally. Every other attribute proxies
    straight through. Lets BE-17's forced-commit-failure sagas (compensating
    delete_user) be driven through the real router/service/repository stack
    over a real (in-memory) DB, instead of mocking the ORM."""

    def __init__(self, real_session, *, fail_times: int = 1, order: list[str] | None = None) -> None:
        self._real = real_session
        self._fail_times = fail_times
        self._order = order

    def commit(self):
        if self._fail_times > 0:
            self._fail_times -= 1
            raise RuntimeError("forced commit failure (test double)")
        if self._order is not None:
            self._order.append("commit")
        return self._real.commit()

    def __getattr__(self, name):
        return getattr(self._real, name)


