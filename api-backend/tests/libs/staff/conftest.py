@contextmanager
def count_queries(engine: Engine) -> _Iterator019[list[str]]:
    """Counts SQL statements executed against `engine` for the duration of the
    `with` block. `len(calls)` is the exact-query-count assertion BE-16 needs.
    Uses SQLAlchemy's own event hook -- no query-counting dependency added."""
    calls: list[str] = []

    def _before(conn, cursor, statement, parameters, context, executemany) -> None:
        calls.append(statement)

    event.listen(engine, "before_cursor_execute", _before)
    try:
        yield calls
    finally:
        event.remove(engine, "before_cursor_execute", _before)


